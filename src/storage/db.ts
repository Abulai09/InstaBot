import pg from 'pg';
import { drizzle } from 'drizzle-orm/node-postgres';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';

/**
 * Тип базы намеренно driver-agnostic: `PgDatabase` — общий предок и пула
 * `node-postgres` (прод), и PGlite (тесты), и транзакции. Благодаря этому
 * функция из `queries/` принимает и базу, и `tx` внутри транзакции, а тесты
 * не тянут в проект сетевой драйвер.
 */
export type AppDb = PgDatabase<PgQueryResultHKT, Record<string, never>>;

/**
 * `close` возвращается вместе с базой, потому что пул держит открытые сокеты
 * и не даёт процессу завершиться. Серверу это безразлично — он и так живёт
 * вечно, — а вот скрипт (`seed`, `owner`) без него просто повиснет после
 * последней строки, чего с синхронным SQLite не бывало.
 */
export interface Database {
  db: AppDb;
  close: () => Promise<void>;
  warmUp: (connections: number) => Promise<void>;
}

/**
 * Пул, а не одно соединение: процесс долгоживущий, и веб-запрос не должен
 * ждать, пока воркер закончит свой запрос.
 *
 * Внешние ключи в Postgres проверяются всегда — прагмы, как у SQLite, здесь нет.
 * Миграции при старте не применяются: при нескольких копиях процесса это гонка,
 * поэтому `npm run migrate` — отдельный шаг перед запуском.
 */
export function openDb(url: string): Database {
  const pool = new pg.Pool({
    connectionString: url,
    // Простаивающее соединение не закрывается. По умолчанию `pg` рвёт его
    // через 10 секунд, и следующий клик пользователя оплачивает новое
    // рукопожатие TLS — на облачной базе за океаном это несколько секунд
    // на ровном месте, притом только у того, кто не спешит.
    // Соединений мало и они свои: держать их открытыми дешевле, чем открывать
    idleTimeoutMillis: 0,
    // TCP keep-alive: без него NAT или балансировщик молча выбрасывает
    // долго молчавший сокет, и «живое» соединение из пула оказывается мёртвым
    keepAlive: true,
    // Запрос не должен ждать соединения бесконечно: лучше честная ошибка,
    // чем висящая вкладка. По умолчанию здесь ноль, то есть без предела
    connectionTimeoutMillis: 15_000,
  });

  /**
   * Открывает соединения заранее, до первого посетителя.
   *
   * Страница кабинета шлёт несколько независимых запросов разом, и пул под
   * них открывает по соединению на запрос. Без прогрева за эти рукопожатия
   * TLS платит первый, кто зашёл после запуска, — на удалённой базе это
   * несколько секунд. Пусть лучше их платит старт процесса.
   *
   * Ошибка здесь не должна ронять сервер: не прогрелись — просто будет
   * медленнее, а настоящая проблема с базой вылезет на первом же запросе
   * с внятным сообщением.
   */
  async function warmUp(connections: number): Promise<void> {
    try {
      // Запросы должны идти одновременно: по очереди они переиспользуют
      // одно и то же соединение, и пул так и останется с одним
      await Promise.all(
        Array.from({ length: connections }, () => pool.query('select 1')),
      );
    } catch {
      // Объект ошибки драйвера не логируется целиком никогда (S4, S9)
    }
  }

  return { db: drizzle(pool), close: () => pool.end(), warmUp };
}
